def test_sheet_selection_defaults_to_first(roster_xls):
    name, _table = xls_adapter.rows(roster_xls)
    assert name == "运动员"


def test_sheet_selection_explicit(roster_xls):
    name, table = xls_adapter.rows(roster_xls, sheet="教练组")
    assert name == "教练组"
    assert table[0] == ["序号", "姓名", "出生日期"]


def test_missing_sheet_rejected(roster_xls):
    with pytest.raises(ValueError):
        xls_adapter.rows(roster_xls, sheet="NoSuchSheet")


def test_missing_file_rejected(tmp_path):
    with pytest.raises(FileNotFoundError):
        xls_adapter.rows(tmp_path / "gone.xls")


def test_athletes_21_data_rows(roster_xls):
    _name, table = xls_adapter.rows(roster_xls, sheet="运动员")
    data = table[2:23]  # after merged title row + header row
    assert len(data) == 21
    assert [row[0] for row in data] == list(range(1, 22))
    assert all(row[1] for row in data)  # names present
    assert all(isinstance(row[2], datetime.date) for row in data)


def test_coaches_16_data_rows(roster_xls):
    _name, table = xls_adapter.rows(roster_xls, sheet="教练组")
    data = table[1:17]  # after header row
    assert len(data) == 16
    assert [row[0] for row in data] == list(range(1, 17))
    assert all(isinstance(row[2], datetime.date) for row in data)


def test_date_conversion_preserves_raw(roster_xls):
    _name, grid = xls_adapter.read_cells(roster_xls, sheet="运动员")
    cell = grid[2][2]  # first data row, birth-date column
    assert cell.ctype == xls_adapter.XL_CELL_DATE
    assert cell.value == datetime.date(1995, 1, 1)
    assert cell.raw == 34700.0  # the untouched Excel serial
    assert cell.value != cell.raw


def test_merged_title_forward_filled_with_flag(roster_xls):
    _name, grid = xls_adapter.read_cells(roster_xls, sheet="运动员")
    title = "一队人员信息（合成测试）"
    assert [c.value for c in grid[0]] == [title, title, title]
    assert grid[0][0].merged is False
    assert grid[0][1].merged is True
    assert grid[0][2].merged is True


def test_empty_row_preserved_not_dropped(roster_xls):
    _name, table = xls_adapter.rows(roster_xls, sheet="运动员")
    assert len(table) == 25  # nothing silently dropped
    assert table[23] == [None, None, None]  # the empty row survives
    assert table[24][0] == 22  # row after the empty one still readable


def test_plain_text_rejected_fail_closed(tmp_path):
    bad = tmp_path / "not-excel.xls"
    bad.write_text("this is not a BIFF file")
    with pytest.raises(xls_adapter.XlsFormatError):
        xls_adapter.rows(bad)


def test_xlsx_rejected_fail_closed(tmp_path):
    fake = tmp_path / "fake.xls"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr("[Content_Types].xml", "<Types/>")
    fake.write_bytes(buf.getvalue())
    with pytest.raises(xls_adapter.XlsFormatError):
        xls_adapter.rows(fake)


def test_rows_returns_plain_values(roster_xls):
    _name, table = xls_adapter.rows(roster_xls, sheet="教练组")
    assert isinstance(table[1][2], datetime.date)
    assert table[1][0] == 1
